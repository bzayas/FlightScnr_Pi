UNPAVED = re.compile(r"TURF|GRS|GRAS|GRE|GVL|GRV|DIRT|GRAV|SAND|WATER|SNOW|ICE|CLAY|SOIL|MATS|GRAVEL|U$", re.I)
MIN_RUNWAY_FT = 2500
MIN_AIRPORT_LONGEST_FT = 4000


def _f(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def load_runways():
    rows = list(csv.DictReader((PI_ASSETS / "data" / "runways.csv").open(encoding="utf-8")))
    out = []
    for r in rows:
        la1, lo1 = _f(r["le_latitude_deg"]), _f(r["le_longitude_deg"])
        la2, lo2 = _f(r["he_latitude_deg"]), _f(r["he_longitude_deg"])
        if None in (la1, lo1, la2, lo2) or r.get("closed") == "1":
            continue
        out.append({
            "ident": r["airport_ident"].strip().upper(),
            "len": _f(r["length_ft"]) or 0,
            "surface": r["surface"] or "",
            "pts": (la1, lo1, la2, lo2),
        })
    return out


def airport_centers(runways) -> dict[str, tuple[float, float]]:
    acc: dict[str, list[float]] = {}
    for r in runways:
        la1, lo1, la2, lo2 = r["pts"]
        s = acc.setdefault(r["ident"], [0.0, 0.0, 0])
        s[0] += la1 + la2
        s[1] += lo1 + lo2
        s[2] += 2
    return {k: (v[0] / v[2], v[1] / v[2]) for k, v in acc.items()}


def gen_airports(runways) -> None:
    by_apt: dict[str, list] = {}
    for r in runways:
        if r["len"] < MIN_RUNWAY_FT or UNPAVED.search(r["surface"] or ""):
            continue
        if len(r["ident"]) != 4 or not r["ident"].isalpha():
            continue  # ICAO-style idents only (labels stay short and meaningful)
        by_apt.setdefault(r["ident"], []).append(r)

    airports = []
    for ident, rws in by_apt.items():
        if max(r["len"] for r in rws) < MIN_AIRPORT_LONGEST_FT:
            continue
        lat = sum(p for r in rws for p in (r["pts"][0], r["pts"][2])) / (2 * len(rws))
        lon = sum(p for r in rws for p in (r["pts"][1], r["pts"][3])) / (2 * len(rws))
        segs = []
        for r in rws:
            la1, lo1, la2, lo2 = r["pts"]
            d = [round((la1 - lat) * 1e5), round((lo1 - lon) * 1e5),
                 round((la2 - lat) * 1e5), round((lo2 - lon) * 1e5)]
            if all(-32767 <= v <= 32767 for v in d):
                segs.append(d)
        if segs:
            longest = int(max(r["len"] for r in rws))
            airports.append((lat, lon, ident, longest, segs))
    airports.sort(key=lambda a: a[0])

    hdr = HEADER + """
#pragma once
#include <stdint.h>

// Paved runways >= 2500 ft at ICAO airports whose longest runway >= 4000 ft,
// from flightscnr/assets/data/runways.csv (OurAirports, public domain).
// Sorted by latitude so a radar view can binary-search its band.
struct AirportRec {
  int32_t lat_e5;      // degrees * 1e5
  int32_t lon_e5;
  char ident[4];       // ICAO, not NUL-terminated
  uint16_t rwy_first;  // index into RUNWAYS
  uint8_t rwy_count;
  uint8_t longest_kft; // longest runway, thousands of feet
};

struct RunwayRec {     // endpoints relative to the airport, degrees * 1e5
  int16_t dlat1, dlon1, dlat2, dlon2;
};

extern const AirportRec AIRPORTS[];
extern const uint16_t AIRPORTS_COUNT;
extern const RunwayRec RUNWAYS[];
"""
    write(OUT_SRC / "airports.h", hdr)

    src = HEADER + '\n#include "airports.h"\n\nconst AirportRec AIRPORTS[] = {\n'
    rw_lines = []
    idx = 0
    for lat, lon, ident, longest, segs in airports:
        src += (f'  {{{round(lat * 1e5)}, {round(lon * 1e5)}, {{\'{ident[0]}\',\'{ident[1]}\','
                f'\'{ident[2]}\',\'{ident[3]}\'}}, {idx}, {len(segs)}, {min(255, longest // 1000)}}},\n')
        for d in segs:
            rw_lines.append("  {" + ", ".join(str(v) for v in d) + "},")
        idx += len(segs)
    src += f"}};\n\nconst uint16_t AIRPORTS_COUNT = {len(airports)};\n\n"
    src += "const RunwayRec RUNWAYS[] = {\n" + "\n".join(rw_lines) + "\n};\n"
    write(OUT_SRC / "airports.cpp", src)
    print(f"  {len(airports)} airports, {idx} runways "
          f"(~{(len(airports) * 16 + idx * 8) / 1024:.0f} KB flash)")


