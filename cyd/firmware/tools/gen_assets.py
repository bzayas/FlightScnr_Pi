HELI = {"helicopter", "military-helicopter"}
# Icon side in px at category scale 1.0. The Pi draws a 30 px icon on a
# 390-unit dial; the CYD radar is ~300 px across, so ~23 px keeps the same
# proportion. A little larger reads better on the lower-dpi TN panel.
ICON_BASE_PX = 30


def _crop_alpha(a: np.ndarray, pad: int = 2) -> np.ndarray:
    ys, xs = np.nonzero(a > 8)
    if len(xs) == 0:
        return a
    y0, y1 = max(0, ys.min() - pad), min(a.shape[0], ys.max() + pad + 1)
    x0, x1 = max(0, xs.min() - pad), min(a.shape[1], xs.max() + pad + 1)
    return a[y0:y1, x0:x1]


def _strip_static_rotor(a: np.ndarray) -> np.ndarray:
    """Port of aircraft_type_icons._strip_static_rotor (erase the baked X)."""
    h, w = a.shape
    out = a.copy()
    spans = [(int((row > 20).nonzero()[0].max() - (row > 20).nonzero()[0].min() + 1)
              if (row > 20).any() else 0) for row in a]
    wide = int(w * 0.30)
    tail_rows = [y for y in range(int(h * 0.70), h) if spans[y] >= wide]
    tail_top = min(tail_rows) if tail_rows else h
    cols = np.nonzero((a > 20).any(axis=0))[0]
    cx = (cols[0] + cols[-1]) / 2.0 if len(cols) else w / 2.0
    cabin_half = max(6, int(round(w * 0.14)))
    xs = np.arange(w)
    mask = np.abs(xs - cx) > cabin_half
    out[: min(tail_top, h), mask] = 0
    return out


def _fit(a: np.ndarray, side: int) -> np.ndarray:
    h, w = a.shape
    scale = side / max(w, h)
    nw, nh = max(1, round(w * scale)), max(1, round(h * scale))
    img = Image.fromarray(a, "L").resize((nw, nh), Image.LANCZOS)
    canvas = Image.new("L", (side, side), 0)
    canvas.paste(img, ((side - nw) // 2, (side - nh) // 2))
    return np.asarray(canvas, dtype=np.uint8)


def gen_aircraft_icons() -> None:
    icon_dir = PI_ASSETS / "aircraft" / "icons"
    mapping = json.loads((icon_dir / "aircraft-icons.json").read_text())["typeCodeMapping"]
    cat_index = {name: i for i, (name, _) in enumerate(CATEGORIES)}

    masks = []
    for name, scale in CATEGORIES:
        im = Image.open(icon_dir / f"{name}.png").convert("RGBA")
        a = np.asarray(im)[:, :, 3]
        a = _crop_alpha(a)
        if name in HELI:
            a = _crop_alpha(_strip_static_rotor(a))
        side = max(8, int(round(ICON_BASE_PX * scale)))
        masks.append((name, side, _fit(a, side)))

    codes: dict[str, int] = {}
    for cat, types in mapping.items():
        if cat.startswith("_") or cat not in cat_index:
            continue
        for code in types:
            key = "".join(ch for ch in str(code).upper() if ch.isalnum())
            if key and len(key) <= 4 and key not in codes:
                codes[key] = cat_index[cat]
    table = sorted(codes.items())

    hdr = HEADER + """
#pragma once
#include <stdint.h>

// Aircraft silhouette masks (8-bit alpha, nose up), cropped and scaled exactly
// like flightscnr/display/round_touch/aircraft_type_icons.py.
enum AircraftIcon : uint8_t {
"""
    for i, (name, _) in enumerate(CATEGORIES):
        hdr += f"  ICON_{name.upper().replace('-', '_')} = {i},\n"
    hdr += f"  ICON_COUNT = {len(CATEGORIES)}\n}};\n\n"
    hdr += """struct AircraftIconMask {
  uint8_t side;          // square mask side in px
  const uint8_t* alpha;  // side*side bytes
};

struct AircraftTypeEntry {
  char code[5];          // ICAO type designator, upper-case alnum
  uint8_t icon;          // AircraftIcon
};

extern const AircraftIconMask AIRCRAFT_ICONS[ICON_COUNT];
extern const AircraftTypeEntry AIRCRAFT_TYPES[];
extern const uint16_t AIRCRAFT_TYPES_COUNT;
"""
    write(OUT_SRC / "aircraft_icons.h", hdr)

    src = HEADER + '\n#include "aircraft_icons.h"\n\n'
    for name, side, m in masks:
        ident = name.upper().replace("-", "_")
        src += f"static const uint8_t MASK_{ident}[{side * side}] = {{\n{c_bytes(m.tobytes())}\n}};\n\n"
    src += "const AircraftIconMask AIRCRAFT_ICONS[ICON_COUNT] = {\n"
    for name, side, _ in masks:
        src += f"  {{{side}, MASK_{name.upper().replace('-', '_')}}},\n"
    src += "};\n\nconst AircraftTypeEntry AIRCRAFT_TYPES[] = {\n"
    for code, idx in table:
        src += f'  {{"{code}", {idx}}},\n'
    src += f"}};\n\nconst uint16_t AIRCRAFT_TYPES_COUNT = {len(table)};\n"
    write(OUT_SRC / "aircraft_icons.cpp", src)

    # Large nose-up airliner for the splash, detail sheet and complications.
    big = _crop_alpha(np.asarray(Image.open(icon_dir / "medium-jet.png").convert("RGBA"))[:, :, 3])
    glyph = _fit(big, 56)
    hdr_glyph = "\n/* 56x56 medium-jet silhouette for UI glyphs. */\nextern const uint8_t PLANE_GLYPH_56[56 * 56];\n"
    write(OUT_SRC / "aircraft_icons.h", (OUT_SRC / "aircraft_icons.h").read_text() + hdr_glyph)
    with (OUT_SRC / "aircraft_icons.cpp").open("a", encoding="utf-8") as fh:
        fh.write(f"\nconst uint8_t PLANE_GLYPH_56[56 * 56] = {{\n{c_bytes(glyph.tobytes())}\n}};\n")

    # Preview sheet for docs / review (not used by the firmware).
    sheet = Image.new("L", (40 * len(masks), 40), 0)
    for i, (_, side, m) in enumerate(masks):
        sheet.paste(Image.fromarray(m, "L"), (i * 40 + (40 - side) // 2, (40 - side) // 2))
    sheet.save(HERE / "aircraft_icons_preview.png")


