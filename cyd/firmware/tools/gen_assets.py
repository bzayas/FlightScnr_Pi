# IANA -> POSIX TZ strings (TZif v2+ footer), for the installer + portal
# ---------------------------------------------------------------------------

def gen_tz() -> None:
    base = Path("/usr/share/zoneinfo")
    zones = {}
    for path in base.rglob("*"):
        rel = path.relative_to(base).as_posix()
        if path.is_dir() or rel.startswith(("posix/", "right/")) or "." in path.name:
            continue
        if not rel[0].isupper():
            continue
        try:
            data = path.read_bytes()
        except OSError:
            continue
        if data[:4] != b"TZif" or data[4:5] not in (b"2", b"3", b"4"):
            continue
        footer = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii", "ignore")
        if footer and not footer.startswith("TZif"):
            zones[rel] = footer
    # Legacy aliases ("L target alias") that browsers still report, e.g.
    # Chrome's Asia/Calcutta. Slim tzdata installs omit the link files.
    zi = base / "tzdata.zi"
    if zi.exists():
        for line in zi.read_text().splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[0] == "L" and parts[1] in zones:
                zones.setdefault(parts[2], zones[parts[1]])
    zones = dict(sorted(zones.items()))
    js = HEADER + "\n// IANA time zone -> POSIX TZ rule for the ESP32 (from the system tzdata).\n"
    js += "export const TZ_POSIX = " + json.dumps(zones, separators=(",", ":")) + ";\n"
    write(INSTALLER / "js" / "tz_posix.js", js)
    print(f"  {len(zones)} zones")


